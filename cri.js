// 色温度 T の基準の光
export function planck(T) {
  const c2 = 1.4388e-2;
  return BANDS.map((l) => { const m = l * 1e-9; return 1 / (m ** 5 * (Math.exp(c2 / (m * T)) - 1)); });
}
export function daylight(T) {
  const xD = T <= 7000 ? -4.607e9 / T ** 3 + 2.9678e6 / T ** 2 + 0.09911e3 / T + 0.244063 : -2.0064e9 / T ** 3 + 1.9018e6 / T ** 2 + 0.24748e3 / T + 0.23704;
  const yD = -3 * xD * xD + 2.87 * xD - 0.275;
  const M = 0.0241 + 0.2562 * xD - 0.7341 * yD;
  const M1 = (-1.3515 - 1.7703 * xD + 5.9114 * yD) / M, M2 = (0.03 - 31.4424 * xD + 30.0717 * yD) / M;
  return BANDS.map((_, i) => S.S0[i] + M1 * S.S1[i] + M2 * S.S2[i]);
}

// 分光分布 spd の下の反射率 R の XYZ(光源そのものの Y = 100)
function xyz(spd, R) {
  const c = cmf();
  const k = 100 / c.reduce((a, row, i) => a + row[1] * spd[i], 0);
  return [0, 1, 2].map((j) => k * c.reduce((a, row, i) => a + row[j] * spd[i] * (R ? R[i] : 1), 0));
}
const uv = ([X, Y, Z]) => { const d = X + 15 * Y + 3 * Z; return [(4 * X) / d, (6 * Y) / d]; };

// 色温度: 黒体の線(CIE 1960 uv)で一番近い点を、log T で黄金分割探索
export function cct(spd) {
  const [u0, v0] = uv(xyz(spd));
  const dist = (lt) => { const [u, v] = uv(xyz(planck(Math.exp(lt)))); return Math.hypot(u - u0, v - v0); };
  let a = Math.log(1000), b = Math.log(25000);
  const g = (Math.sqrt(5) - 1) / 2;
  for (let i = 0; i < 80; i++) {
    const c = b - g * (b - a), d = a + g * (b - a);
    if (dist(c) < dist(d)) b = d; else a = c;
  }
  const T = Math.exp((a + b) / 2);
  return { T, duv: dist(Math.log(T)) };
}

export function cri(spd) {
  const { T, duv } = cct(spd);
  const ref = T < 5000 ? planck(T) : daylight(T);
  const cd = ([u, v]) => [(4 - u - 10 * v) / v, (1.708 * v + 0.404 - 1.481 * u) / v];
  const [ck, dk] = cd(uv(xyz(spd))), [cr, dr] = cd(uv(xyz(ref)));
  const [ur, vr] = uv(xyz(ref));
  const W = (Y) => 25 * Math.cbrt(Y) - 17;
  const R = TCS.map((t) => {
    const xr = xyz(ref, t), xt = xyz(spd, t);
    const [uri, vri] = uv(xr);
    const [cki, dki] = cd(uv(xt));
    const den = 16.518 + (1.481 * cr * cki) / ck - (dr * dki) / dk;
    const ut = (10.872 + (0.404 * cr * cki) / ck - (4 * dr * dki) / dk) / den, vt = 5.52 / den;
    const Wr = W(xr[1]), Wt = W(xt[1]);
    const Ur = 13 * Wr * (uri - ur), Vr = 13 * Wr * (vri - vr), Ut = 13 * Wt * (ut - ur), Vt = 13 * Wt * (vt - vr);
    return 100 - 4.6 * Math.hypot(Ur - Ut, Vr - Vt, Wr - Wt);
  });
  return { T, duv, R, Ra: R.slice(0, 8).reduce((a, b) => a + b) / 8 };
}
